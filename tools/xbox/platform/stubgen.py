"""Generate logging stand-in DLLs for imports nothing on this PC provides.

usage: stubgen.py <needs.json> <out_dir>      needs.json = {"dll name": ["ExportName" | "#ordinal", ...]}  (exe_report.py writes it)

For every DLL it writes <out_dir>/<dll>.cpp, <dll>.def and build.bat. Each export is a stub that logs
    <dll>!<name>(rcx, rdx, r8, r9)
to the file named by the STUB_LOG environment variable (stderr when unset) and returns 0 (NULL / FALSE / S_OK). The four values are the
integer argument registers of the x64 calling convention, which is all that can be known without a signature; floating-point and
stack arguments are not shown. The trace of a first run therefore says WHICH functions the game calls, in which order and with
what leading arguments; it does not say what they should do. Replace a stub with a real implementation once its behaviour is known
(xmem.cpp and d3d12_xs.cpp in this directory are examples made that way).

Exports are declared through the .def file as aliases (ExportName=stub_N), so C++ mangled names and ordinal-only imports work.
Environment: STUB_LOG=<file>; STUB_ABORT=<substring> calls DebugBreak/exits when a function whose name contains the text is hit.
"""
import json, os, sys

CPP = r'''// generated by stubgen.py for {dll}: {count} exports, all logging stubs returning 0
#include <windows.h>
#include <cstdio>
static void Trace(const char* name, ULONGLONG a, ULONGLONG b, ULONGLONG c, ULONGLONG d) {{
    char path[MAX_PATH];
    FILE* f = nullptr;
    const bool toFile = GetEnvironmentVariableA("STUB_LOG", path, sizeof(path)) != 0;
    if (toFile) fopen_s(&f, path, "a");
    if (!f) f = stderr;
    fprintf(f, "{dll}!%s(0x%llx, 0x%llx, 0x%llx, 0x%llx) tid=%lu\n", name, a, b, c, d, GetCurrentThreadId());
    if (f != stderr) fclose(f);
    char stop[128];
    if (GetEnvironmentVariableA("STUB_ABORT", stop, sizeof(stop)) && strstr(name, stop)) {{ fflush(stderr); TerminateProcess(GetCurrentProcess(), 0xdead); }}
}}
extern "C" {{
{body}
}}
'''


def safe(s):
    return ''.join(c if c.isalnum() else '_' for c in s)


def generate(needs, out):
    os.makedirs(out, exist_ok=True)
    build = ['@echo off', 'rem run from a Visual Studio x64 developer prompt']
    for dll, names in sorted(needs.items()):
        stem = dll[:-4] if dll.lower().endswith('.dll') else dll
        body, defs = [], ['LIBRARY ' + stem, 'EXPORTS']
        for i, n in enumerate(sorted(set(names))):
            label = n.replace('\\', '\\\\').replace('"', '\\"')
            body.append('__declspec(noinline) ULONGLONG stub_%d(ULONGLONG a, ULONGLONG b, ULONGLONG c, ULONGLONG d) { Trace("%s", a, b, c, d); return 0; }' % (i, label))
            defs.append('  %s=stub_%d' % (n, i) if not n.startswith('#') else '  stub_%d @%s NONAME' % (i, n[1:]))
        open(os.path.join(out, stem + '.cpp'), 'w').write(CPP.format(dll=stem, count=len(body), body='\n'.join(body)))
        open(os.path.join(out, stem + '.def'), 'w').write('\n'.join(defs) + '\n')
        build.append('cl /nologo /LD /O1 %s.cpp /Fe:%s.dll /link /DLL /DEF:%s.def' % (stem, stem, stem))
    open(os.path.join(out, 'build.bat'), 'w').write('\r\n'.join(build) + '\r\n')
    return sorted(needs)


if __name__ == '__main__':
    needs = json.load(open(sys.argv[1]))
    print('wrote stubs for', generate(needs, sys.argv[2]))
